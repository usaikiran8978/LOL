-- 0003 Identity, authentication, sessions, devices, consent.
-- BRD §6 (phone/email/social auth, age & consent), BRD §15 (phone/email verification),
-- TECH §15 (short-lived tokens, secure refresh, brute-force, device/session mgmt), TECH §16 (consent records).

CREATE TABLE users (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email              citext UNIQUE,
  phone_e164         text   UNIQUE CHECK (phone_e164 ~ '^\+[1-9][0-9]{6,14}$'),
  password_hash      text,
  status             text   NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending','active','restricted','suspended','banned','deactivated','deleted')),
  status_reason      text,
  status_until       timestamptz,            -- for time-boxed suspensions
  date_of_birth      date,
  age_verified_at    timestamptz,
  email_verified_at  timestamptz,
  phone_verified_at  timestamptz,
  country_code       char(2) REFERENCES countries(code),
  locale             text NOT NULL DEFAULT 'en',
  timezone           text,
  failed_login_count int  NOT NULL DEFAULT 0,
  locked_until       timestamptz,
  last_login_at      timestamptz,
  last_active_at     timestamptz,
  token_version      int  NOT NULL DEFAULT 0,  -- bump to force-logout all sessions
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  deleted_at         timestamptz,
  CONSTRAINT users_has_identifier CHECK (email IS NOT NULL OR phone_e164 IS NOT NULL OR status = 'deleted')
);
SELECT add_updated_at_trigger('users');
CREATE INDEX users_status_idx ON users (status) WHERE deleted_at IS NULL;
CREATE INDEX users_created_idx ON users (created_at);

-- Social / OIDC identities (Google, Apple, Facebook ...).
CREATE TABLE auth_identities (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id          uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  provider         text NOT NULL CHECK (provider IN ('google','apple','facebook')),
  provider_subject text NOT NULL,
  email            citext,
  created_at       timestamptz NOT NULL DEFAULT now(),
  last_used_at     timestamptz,
  UNIQUE (provider, provider_subject)
);
CREATE INDEX auth_identities_user_idx ON auth_identities (user_id);

-- Devices: one row per physical install. Push tokens hang off devices.
CREATE TABLE user_devices (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id       uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  installation_id text NOT NULL,          -- generated by the app on first launch
  platform      text NOT NULL CHECK (platform IN ('ios','android','web')),
  model         text,
  os_version    text,
  app_version   text,
  push_token    text,
  push_provider text CHECK (push_provider IN ('fcm','apns')),
  push_token_updated_at timestamptz,
  trusted       boolean NOT NULL DEFAULT false,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at  timestamptz NOT NULL DEFAULT now(),
  revoked_at    timestamptz,
  UNIQUE (user_id, installation_id)
);
CREATE INDEX user_devices_push_idx ON user_devices (push_token) WHERE push_token IS NOT NULL;

-- Sessions + rotating refresh tokens. Only SHA-256 hashes of refresh tokens are stored.
CREATE TABLE user_sessions (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id       uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  device_id     uuid REFERENCES user_devices(id) ON DELETE SET NULL,
  ip            inet,
  user_agent    text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  last_used_at  timestamptz NOT NULL DEFAULT now(),
  expires_at    timestamptz NOT NULL,
  revoked_at    timestamptz,
  revoke_reason text
);
CREATE INDEX user_sessions_user_active_idx ON user_sessions (user_id) WHERE revoked_at IS NULL;

CREATE TABLE refresh_tokens (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id  uuid NOT NULL REFERENCES user_sessions(id) ON DELETE CASCADE,
  token_hash  bytea NOT NULL UNIQUE,
  parent_id   uuid REFERENCES refresh_tokens(id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL,
  used_at     timestamptz,           -- set when rotated; re-use of a used token revokes the session (reuse detection)
  revoked_at  timestamptz
);
CREATE INDEX refresh_tokens_session_idx ON refresh_tokens (session_id);

-- One-time codes / tokens for email+phone verification, password reset, account recovery, login OTP.
CREATE TABLE verification_codes (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id     uuid REFERENCES users(id) ON DELETE CASCADE,
  channel     text NOT NULL CHECK (channel IN ('email','sms')),
  destination text NOT NULL,           -- normalized email or E.164
  purpose     text NOT NULL CHECK (purpose IN ('verify_email','verify_phone','login_otp','password_reset','account_recovery','change_email','change_phone')),
  code_hash   bytea NOT NULL,
  attempts    smallint NOT NULL DEFAULT 0,
  max_attempts smallint NOT NULL DEFAULT 5,
  created_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL,
  consumed_at timestamptz,
  ip          inet
);
CREATE INDEX verification_codes_lookup_idx ON verification_codes (destination, purpose, created_at DESC) WHERE consumed_at IS NULL;

-- Legal documents (terms, privacy policy, community guidelines) — versioned, per locale, admin-managed.
CREATE TABLE legal_documents (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  doc_type     text NOT NULL CHECK (doc_type IN ('terms','privacy','community_guidelines','safety','cookie','ai_terms')),
  version      int  NOT NULL,
  locale       text NOT NULL REFERENCES languages(code),
  country_code char(2) REFERENCES countries(code),   -- NULL = global
  title        text NOT NULL,
  body_md      text NOT NULL,
  status       text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  effective_at timestamptz,
  requires_reacceptance boolean NOT NULL DEFAULT false,
  created_by   uuid,
  created_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE NULLS NOT DISTINCT (doc_type, version, locale, country_code)
);

-- Consent records (TECH §16). Append-only history; current state = latest row per (user, consent_type).
CREATE TABLE consent_records (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id           uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  consent_type      text NOT NULL CHECK (consent_type IN (
                      'terms','privacy','age_confirmation','location','precise_location','crossed_paths',
                      'marketing_email','marketing_push','marketing_sms','ai_assistance','ai_sensitive_data',
                      'sensitive_profile_data','analytics','biometric_verification','identity_verification','calendar')),
  granted           boolean NOT NULL,
  legal_document_id uuid REFERENCES legal_documents(id),
  source            text NOT NULL DEFAULT 'app' CHECK (source IN ('app','web','admin','import')),
  ip                inet,
  user_agent        text,
  created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX consent_records_user_type_idx ON consent_records (user_id, consent_type, created_at DESC);
